'use strict';
const fs = require('node:fs');
const path = require('node:path');
const data = JSON.parse(fs.readFileSync(path.join(__dirname, 'mk300-v75-confirmed.json'), 'utf8'));
const source = `// Generated by build-v75.cjs. Legacy V73 data remains unchanged.
(function(root){
  'use strict';
  const definition = ${JSON.stringify(data)};
  const legacy = root.MK300V73;
  const parameters = JSON.parse(JSON.stringify(root.MK300V73Parameters));
  const amp = [...legacy.AMP_CATALOG], ds = [...legacy.DS_CATALOG], cab = {...legacy.CAB_SLOT_NAMES};
  for (const item of definition.confirmed_models) {
    const models = parameters.blocks[item.block].models;
    const model = models[item.index] || {index:item.index, knobs:[...models[0].knobs]};
    models[item.index] = {...model, name:item.name, verification:'owner_export', evidence:item.evidence};
    if (item.block === 3) ds[item.index] = item.name;
    if (item.block === 4) amp[item.index] = item.name;
    if (item.block === 5) cab[item.index + 1] = item.name;
  }
  for (const index of definition.nam.observed_indices) {
    const model = parameters.blocks[4].models[index];
    const name = 'Slot personalizado ' + (index + 1) + ' · nome a confirmar';
    parameters.blocks[4].models[index] = {...model, legacy_name:model.name, name, verification:'custom_slot'};
    amp[index] = name;
  }
  root.MK300V75Catalog = Object.freeze(definition);
  root.MK300V75Parameters = Object.freeze({...parameters, firmware:'v75'});
  root.MK300V75 = Object.freeze({...legacy, firmware:'v75', AMP_CATALOG:amp, DS_CATALOG:ds, CAB_SLOT_NAMES:cab});
})(globalThis);
`;
fs.writeFileSync(path.join(__dirname, 'v75.js'), source);
